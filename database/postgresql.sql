-- PostgreSQL 15+; esquema idempotente da API de estoque.
-- Execute automaticamente via startup ou manualmente em uma base PostgreSQL vazia.
-- Não contém DROP, TRUNCATE nem senhas de demonstração.
CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('ADMIN', 'FUNCIONARIO', 'VENDEDOR')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10,2) NOT NULL DEFAULT 0,
    categoria VARCHAR(100),
    codigo_barras VARCHAR(50),
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS estoque (
    id_estoque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_local VARCHAR(100) NOT NULL,
    descricao VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS estoque_produto (
    id_estoque_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    id_estoque INTEGER NOT NULL REFERENCES estoque(id_estoque),
    quantidade INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_estoque_produto UNIQUE (id_produto, id_estoque)
);

CREATE TABLE IF NOT EXISTS movimentacao_estoque (
    id_movimentacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    id_estoque INTEGER NOT NULL REFERENCES estoque(id_estoque),
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade INTEGER NOT NULL,
    data_movimentacao TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE TABLE IF NOT EXISTS pedidos (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
    id_estoque INTEGER NULL REFERENCES estoque(id_estoque),
    data_pedido TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    status VARCHAR(15) NOT NULL DEFAULT 'ABERTO'
        CHECK (status IN ('ABERTO', 'CONFIRMADO', 'CANCELADO'))
);

CREATE TABLE IF NOT EXISTS itens_pedido (
    id_item_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedidos(id_pedido),
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_produto_nome ON produto(nome);
CREATE INDEX IF NOT EXISTS ix_movimentacao_data ON movimentacao_estoque(data_movimentacao);
CREATE INDEX IF NOT EXISTS ix_pedidos_status ON pedidos(status);

-- Chaves geradas no login e enviadas como X-API-Key. O BD guarda só o hash.
CREATE TABLE IF NOT EXISTS api_sessoes (
    token_hash CHAR(64) PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    criada_em_utc TIMESTAMPTZ NOT NULL,
    expira_em_utc TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_api_sessoes_usuario ON api_sessoes(id_usuario);
CREATE INDEX IF NOT EXISTS ix_api_sessoes_expiracao ON api_sessoes(expira_em_utc);

-- Chaves opcionais para outras aplicações, com escopos limitados.
CREATE TABLE IF NOT EXISTS api_chaves (
    id_chave BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHAR(64) NOT NULL UNIQUE,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    nome VARCHAR(100) NOT NULL,
    escopo VARCHAR(25) NOT NULL CHECK (escopo IN ('LEITURA','ESCRITA_PEDIDOS')),
    criada_em_utc TIMESTAMPTZ NOT NULL,
    expira_em_utc TIMESTAMPTZ NOT NULL,
    revogada_em_utc TIMESTAMPTZ NULL
);
CREATE INDEX IF NOT EXISTS ix_api_chaves_usuario ON api_chaves(id_usuario);
CREATE INDEX IF NOT EXISTS ix_api_chaves_expiracao ON api_chaves(expira_em_utc);
